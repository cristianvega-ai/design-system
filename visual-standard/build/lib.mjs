const MARK = {
  css: (n) => [`/* build:${n} */`, `/* /build:${n} */`],
  html: (n) => [`<!-- build:${n} -->`, `<!-- /build:${n} -->`],
};

export function findRegion(text, name, kind) {
  const [open, close] = MARK[kind](name);
  const count = (s) => text.split(s).length - 1;
  if (count(open) === 0 || count(close) === 0) throw new Error(`marker build:${name}: missing`);
  if (count(open) > 1 || count(close) > 1) throw new Error(`marker build:${name}: duplicate`);
  const start = text.indexOf(open) + open.length;
  const end = text.indexOf(close);
  if (end < start) throw new Error(`marker build:${name}: reversed`);
  return { start, end };
}

export function replaceRegion(text, name, kind, content) {
  const { start, end } = findRegion(text, name, kind);
  return text.slice(0, start) + content + text.slice(end);
}

export function walkTokens(tokens) {
  const groups = [];
  for (const [g, node] of Object.entries(tokens)) {
    if (g.startsWith('$')) continue;
    const keys = Object.keys(node).filter((k) => !k.startsWith('$'));
    groups.push({ name: g, description: node.$description ?? '', keys });
  }
  return groups;
}

export function renderTokenRegion(tokensCss, tokens) {
  const lines = new Map();
  for (const m of tokensCss.matchAll(/^\s*(--([a-z0-9-]+):.*)$/gm)) lines.set(m[2], m[1].trimEnd());
  let out = '\n';
  for (const group of walkTokens(tokens)) {
    if (group.description) out += `    /* ${group.description} */\n`;
    for (const key of group.keys) {
      if (!lines.has(key)) throw new Error(`--${key} is not in tokens.css`);
      out += `    ${lines.get(key)}\n`;
    }
  }
  return out;
}

const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

export function renderTokenBlock(regionText) {
  const out = [':root {'];
  for (const raw of regionText.split('\n')) {
    const line = raw.trim();
    if (!line) continue;
    if (line.startsWith('/*')) { out.push(`  <em>${esc(line)}</em>`); continue; }
    const m = line.match(/^(--[a-z0-9-]+):\s*(.*?);(\s*\/\*.*\*\/)?$/);
    if (!m) throw new Error(`cannot mark up: ${line}`);
    const value = m[2].startsWith('var(') ? esc(m[2]) : `<i>${esc(m[2])}</i>`;
    const comment = m[3] ? ` <em>${esc(m[3].trim())}</em>` : '';
    out.push(`  ${m[1]}: ${value};${comment}`);
  }
  out.push('}');
  return out.join('\n');
}

export function renderGroundContract(stylesheet) {
  const start = stylesheet.indexOf('  .g { background');
  const end = stylesheet.indexOf('  .mono {');
  if (start < 0 || end < 0) throw new Error('ground rules not found in the stylesheet');
  const skip = ['  .g *, .frame__edge *, .frame__main * { box-sizing: border-box; }', '  :is(.g, .frame__edge, .frame__main) :is(h1, h2, h3, h4) {'];
  const lines = stylesheet.slice(start, end).split('\n').filter((l) => l.trim() && !skip.some((s) => l.startsWith(s)));
  return esc(lines.map((l) => l.replace(/^  /, '')).join('\n')).replace(/\/\*.*?\*\//g, (c) => `<em>${c}</em>`) + '\n';
}

const ANCHORS = {
  chromeStart: '    /* documentation chrome · light. Dark redefines these names only. */',
  grounds: '     2. Grounds.',
  specimens: '  /* ---------- foundations specimens ---------- */',
};

const header = (version, date) => `/* Cristian Vega ${version} · ${date} · generated by npm run build; do not edit */\n`;

// The "2. Grounds" and "3. Components" banners share one shape: a text line
// (the anchor) sits inside a boxed comment. This walks back from the text
// line to the "/*" that opens the box, so the slice below starts at the box,
// not partway through it.
function bannerStart(stylesheet, textMark, label) {
  const at = stylesheet.indexOf(textMark);
  if (at < 0) throw new Error(`stylesheet anchor not found: ${label}`);
  return stylesheet.lastIndexOf('/*', at);
}

// The grounds and the components, with the built tokens above them. A product reads this file.
export function extractSystem(stylesheet, tokensCss, version, date) {
  const start = bannerStart(stylesheet, ANCHORS.grounds, '2. Grounds');
  const end = stylesheet.indexOf(ANCHORS.specimens);
  if (end < 0) throw new Error('stylesheet anchor not found: foundations specimens');
  const body = stylesheet.slice(start, end).trimEnd();
  return header(version, date) + tokensCss.trimEnd() + '\n\n' + body + '\n';
}

// The documentation tokens, the base rules, and the documentation furniture. A document reads this file.
// This slice starts inside the sheet's :root (its first lines are custom-property
// declarations) and already carries that block's closing "}", so a fresh ":root {"
// is prefixed here to keep the emitted file balanced and parseable.
export function extractChrome(stylesheet, version, date) {
  const start = stylesheet.indexOf(ANCHORS.chromeStart);
  if (start < 0) throw new Error('stylesheet anchor not found: documentation chrome');
  const end = bannerStart(stylesheet, ANCHORS.grounds, '2. Grounds');
  const body = stylesheet.slice(start, end).trimEnd();
  return header(version, date) + ':root {\n' + body + '\n';
}

// The two product-facing stylesheets, taken from one built sheet. The build writes them into
// dist/, and the drift check compares dist/ against a fresh extraction, so both call this one
// function and cannot read the sheet differently.
export function extractStylesheets(sheet, tokensCss, version, date) {
  const open = '<style>';
  const start = sheet.indexOf(open);
  const end = sheet.indexOf('</style>');
  if (start < 0 || end < start) throw new Error('the sheet has no first <style> block');
  const stylesheet = sheet.slice(start + open.length, end);
  return {
    systemCss: extractSystem(stylesheet, tokensCss, version, date),
    chromeCss: extractChrome(stylesheet, version, date),
  };
}

export function renderIconSprite(files) {
  const symbols = files.map(({ name, body }) =>
    `<symbol id="i-${name}" viewBox="0 0 16 16" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round">${body.trim()}</symbol>`);
  return `<svg hidden aria-hidden="true">${symbols.join('')}</svg>`;
}

export function stampVersion(text, version, date) {
  const re = /v\d+(?:\.\d+)* · \d{4}-\d{2}-\d{2}/g;
  const n = (text.match(re) ?? []).length;
  if (n !== 2) throw new Error(`expected 2 version stamps, found ${n}`);
  return text.replace(re, `v${version} · ${date}`);
}

export function inject({ sheet, tokensCss, tokens, icons }) {
  let out = sheet;
  const region = renderTokenRegion(tokensCss, tokens);
  out = replaceRegion(out, 'tokens', 'css', region);
  out = replaceRegion(out, 'token-block', 'html', renderTokenBlock(region));
  const styleStart = out.indexOf('<style>');
  const styleEnd = out.indexOf('</style>');
  out = replaceRegion(out, 'ground-contract', 'html', '\n' + renderGroundContract(out.slice(styleStart, styleEnd)));
  out = replaceRegion(out, 'icons', 'html', renderIconSprite(icons));
  const { version, date } = tokens.$extensions['cristian-vega'];
  return stampVersion(out, version, date);
}

// The products document reads the built system. Its own rules follow the two regions.
export function injectProducts({ products, systemCss, chromeCss, icons, version, date }) {
  let out = products;
  out = replaceRegion(out, 'system', 'css', '\n' + systemCss.trimEnd() + '\n');
  out = replaceRegion(out, 'doc-chrome', 'css', '\n' + chromeCss.trimEnd() + '\n');
  out = replaceRegion(out, 'icons', 'html', renderIconSprite(icons));
  return stampVersion(out, version, date);
}
